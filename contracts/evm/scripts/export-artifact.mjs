#!/usr/bin/env node
// Regenerates packages/chains/src/evm/ikaAccountArtifact.ts from the Foundry build output.
// Usage (from contracts/evm): forge build && node scripts/export-artifact.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const evmRoot = resolve(here, '..');
const artifactPath = resolve(evmRoot, 'out/IkaAccount.sol/IkaAccount.json');
const outPath = resolve(evmRoot, '../../packages/chains/src/evm/ikaAccountArtifact.ts');

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
const abi = artifact.abi;
const bytecode = artifact.bytecode?.object;
if (!Array.isArray(abi) || typeof bytecode !== 'string' || !bytecode.startsWith('0x') || bytecode.length < 4) {
  throw new Error(`Unexpected artifact shape in ${artifactPath}; run \`forge build\` first.`);
}

const src = `// AUTO-GENERATED by contracts/evm/scripts/export-artifact.mjs. Do not edit by hand.
// Source: contracts/evm/src/IkaAccount.sol (EIP-7702 delegate for Ika dWallet EOAs).

export const ikaAccountAbi = ${JSON.stringify(abi, null, 2)} as const;

export const ikaAccountBytecode = '${bytecode}' as const;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, src);
console.log(`wrote ${outPath} (${abi.length} ABI entries, ${(bytecode.length - 2) / 2} bytes of creation code)`);
